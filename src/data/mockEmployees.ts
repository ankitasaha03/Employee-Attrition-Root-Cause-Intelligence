export function calculateSimulation(
  employees: Employee[],
  params: SimulationParams
): SimulationResult {
  const currentHighRisk = employees.filter(
    (e) => e.riskLevel === "Critical" || e.riskLevel === "High"
  ).length;

  const currentAttritionRate = 14.8; // Baseline enterprise rate (%)

  // Model reduction factors based on intervention sliders
  // 1. Salary Adjustment: each 1% reduces comp-driven risk by 2.2%
  const salaryFactor = (params.salaryAdjustmentPercent / 20) * 0.38;

  // 2. Overtime reduction: each 10% reduction reduces workload risk by 2.6%
  const overtimeFactor = (params.overtimeReductionPercent / 50) * 0.32;

  // 3. Remote days: reduces commute & flexibility stress
  const remoteFactor = (params.remoteDaysPerWeek / 5) * 0.22;

  // 4. Upskilling & retention bonuses
  const upskillFactor = params.upskillingProgramEnabled ? 0.12 : 0;
  const bonusFactor = Math.min(params.retentionBonusBudget / 250000, 1) * 0.14;

  const totalReductionRatio = Math.min(
    0.68,
    salaryFactor + overtimeFactor + remoteFactor + upskillFactor + bonusFactor
  );

  const predictedAttritionRate = Number(
    Math.max(5.2, currentAttritionRate * (1 - totalReductionRatio)).toFixed(1)
  );

  const rateReduction = Number((currentAttritionRate - predictedAttritionRate).toFixed(1));
  const headcountSaved = Math.round((rateReduction / 100) * 1020); // Scaled to enterprise 1,020 headcount
  const predictedRiskHeadcount = Math.max(8, Math.round(currentHighRisk * (1 - totalReductionRatio * 0.85)));

  // Costs
  // Avg salary ~$148k, base headcount 1,020
  const avgSalary = 148000;
  const salaryIncreaseCost = (params.salaryAdjustmentPercent / 100) * avgSalary * 1020;
  const overtimeInterventionCost = (params.overtimeReductionPercent / 100) * 80000; // hiring temp / load balancing
  const remoteToolsCost = params.remoteDaysPerWeek * 15000;
  const upskillCost = params.upskillingProgramEnabled ? 95000 : 0;

  const interventionCost = Math.round(
    salaryIncreaseCost + overtimeInterventionCost + remoteToolsCost + upskillCost + params.retentionBonusBudget
  );

  const avgCostToReplace = 125000;
  const annualReplacementCostSaved = Math.round(headcountSaved * avgCostToReplace);
  const netSavings = annualReplacementCostSaved - interventionCost;
  const roiPercent = interventionCost > 0 ? Math.round((netSavings / interventionCost) * 100) : 0;

  return {
    currentAttritionRate,
    predictedAttritionRate,
    rateReduction,
    currentRiskHeadcount: currentHighRisk,
    predictedRiskHeadcount,
    headcountSaved,
    annualReplacementCostSaved,
    interventionCost,
    netSavings,
    roiPercent,
  };
}
